export interface PosKeyEvent {
	posKey: number
	pressed: boolean
}

const POSKEY_REPORT_ID = 0x04
const RELEASE_PREFIX = 0xfe
const EXTENDED_PREFIX = 0xe0

/**
 * Hardware codes used by the PrehKeyTec POSKey001...POSKey128 macros.
 * The gaps are intentional: the device uses keyboard scan-code-shaped values,
 * so the macro number cannot be treated as the raw byte value.
 */
const SINGLE_BYTE_CODES: readonly number[] = [
	0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x10, 0x11, 0x12, 0x13,
	0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1e, 0x1f, 0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27,
	0x28, 0x29, 0x2b, 0x2c, 0x2d, 0x2e, 0x2f, 0x30, 0x31, 0x32, 0x33, 0x34, 0x35, 0x3b, 0x3c, 0x3d, 0x3e, 0x3f, 0x40,
	0x41, 0x42, 0x43, 0x44, 0x47, 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f, 0x50, 0x51, 0x52, 0x53, 0x56, 0x57,
	0x58,
]

const EXTENDED_CODES: readonly number[] = [
	0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x11, 0x12, 0x13, 0x14,
	0x15, 0x16, 0x17, 0x18, 0x1a, 0x1b, 0x1e, 0x1f, 0x23, 0x25, 0x26, 0x27, 0x28, 0x29, 0x2b, 0x2c, 0x2d, 0x2f, 0x31,
	0x32, 0x34, 0x39, 0x3b, 0x3c, 0x3d, 0x3e, 0x3f, 0x40, 0x41, 0x42, 0x43, 0x44,
]

function decodePosKey(token: Uint8Array): number | undefined {
	if (token.length === 1) {
		const index = SINGLE_BYTE_CODES.indexOf(token[0])
		return index === -1 ? undefined : index + 1
	}

	if (token.length === 2 && token[0] === EXTENDED_PREFIX) {
		const index = EXTENDED_CODES.indexOf(token[1])
		return index === -1 ? undefined : SINGLE_BYTE_CODES.length + index + 1
	}

	return undefined
}

/**
 * Decode one raw report from the separate PrehKeyTec POSKey HID interface.
 */
export function parsePosKeyReport(report: Uint8Array): PosKeyEvent[] {
	if (report[0] !== POSKEY_REPORT_ID) return []

	let payloadEnd = report.length
	while (payloadEnd > 1 && report[payloadEnd - 1] === 0) payloadEnd -= 1

	const payload = report.subarray(1, payloadEnd)
	if (payload.length === 0) return []

	const pressed = payload[0] !== RELEASE_PREFIX
	const token = pressed ? payload : payload.subarray(1)
	const posKey = decodePosKey(token)

	return posKey === undefined ? [] : [{ posKey, pressed }]
}
